package test

import "time"

// waitFor polls condition until it returns true or timeout is reached.
// used instead of fixed sleeps before assertions: on a fresh kafka broker
// the consumer-group coordination may take several seconds, which made
// these tests flaky with fixed sleeps.
func waitFor(timeout time.Duration, condition func() bool) bool {
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		if condition() {
			return true
		}
		time.Sleep(200 * time.Millisecond)
	}
	return condition()
}
